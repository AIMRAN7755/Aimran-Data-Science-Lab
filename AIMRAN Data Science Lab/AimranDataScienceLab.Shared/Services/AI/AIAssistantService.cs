using System;
using System.Collections.Generic;
using System.Threading.Tasks;
using AimranDataScienceLab.Core.Domain.AI;

namespace AimranDataScienceLab.Core.Services.AI;

/// <summary>
/// AI Assistant Service that intelligently guides users through data science workflows.
/// Provides recommendations, suggestions, and automated insights across all roles.
/// </summary>
public interface IAIAssistantService
{
    Task<AIAssistantResponse> ProcessQueryAsync(AIAssistantRequest request);
    Task<WorkflowRecommendation[]> GetWorkflowRecommendationsAsync(Guid projectId, Guid userId);
    Task<string> GetContextualHelpAsync(string context);
}

/// <summary>
/// Auto Insight Engine that automatically discovers patterns and insights.
/// </summary>
public interface IAutoInsightEngine
{
    Task<AutoGeneratedInsight[]> GenerateInsightsAsync(Guid datasetId);
    Task<AutoGeneratedInsight[]> GetProjectInsightsAsync(Guid projectId);
    Task<bool> ApproveInsightAsync(Guid insightId, Guid approvedByUserId);
    Task<AutoGeneratedInsight?> GetInsightAsync(Guid insightId);
}

/// <summary>
/// Workflow Orchestration Service that manages cross-role coordination.
/// Automatically sequences workflows based on dependencies and role capabilities.
/// </summary>
public interface IWorkflowOrchestrationService
{
    Task<WorkflowExecutionPlan> PlanWorkflowAsync(Guid projectId, WorkflowIntent intent);
    Task<WorkflowExecution> ExecuteWorkflowAsync(Guid workflowPlanId);
    Task<WorkflowExecution?> GetExecutionAsync(Guid executionId);
    Task<WorkflowExecution[]> GetProjectExecutionsAsync(Guid projectId);

    Task<WorkflowStep> GetCurrentStepAsync(Guid executionId);
    Task CompleteCurrentStepAsync(Guid executionId);
    Task SkipStepAsync(Guid executionId, string reason);
}

public class WorkflowIntent
{
    public string Goal { get; set; } = string.Empty; // e.g., "Build a churn prediction model"
    public string[] DataSourceNames { get; set; } = Array.Empty<string>();
    public string TargetVariable { get; set; } = string.Empty;
    public string? EstimatedTimeline { get; set; } // "ASAP", "1 week", "1 month"
    public string[]? BusinessConstraints { get; set; }
    public Guid RequestedByUserId { get; set; }
}

public class WorkflowExecutionPlan
{
    public Guid Id { get; set; }
    public Guid ProjectId { get; set; }
    public WorkflowPhase[] Phases { get; set; } = Array.Empty<WorkflowPhase>();
    public string EstimatedDurationDays { get; set; } = string.Empty;
    public string[] RequiredResources { get; set; } = Array.Empty<string>();
    public string? ContextualAdvice { get; set; }
}

public class WorkflowPhase
{
    public int PhaseNumber { get; set; }
    public string Name { get; set; } = string.Empty;
    public string AssignedRole { get; set; } = string.Empty;
    public WorkflowStep[] Steps { get; set; } = Array.Empty<WorkflowStep>();
    public string? Description { get; set; }
    public int EstimatedDaysToComplete { get; set; }
}

public class WorkflowStep
{
    public Guid Id { get; set; }
    public string Title { get; set; } = string.Empty;
    public string Description { get; set; } = string.Empty;
    public string AssignedRole { get; set; } = string.Empty;

    public string ServiceToCall { get; set; } = string.Empty;
    public Dictionary<string, object> Parameters { get; set; } = new();

    public int Order { get; set; }
    public int EstimatedMinutesToComplete { get; set; }

    public bool IsCompleted { get; set; }
    public DateTime? CompletedAt { get; set; }
}

public class WorkflowExecution
{
    public Guid Id { get; set; }
    public Guid PlanId { get; set; }
    public Guid ProjectId { get; set; }

    public WorkflowExecutionStatus Status { get; set; } = WorkflowExecutionStatus.NotStarted;
    public int CurrentPhaseIndex { get; set; }
    public int CurrentStepIndex { get; set; }

    public int TotalSteps { get; set; }
    public int CompletedSteps { get; set; }
    public int ProgressPercent => (CompletedSteps * 100) / TotalSteps;

    public DateTime StartedAt { get; set; }
    public DateTime? CompletedAt { get; set; }

    public WorkflowExecutionLog[] Logs { get; set; } = Array.Empty<WorkflowExecutionLog>();
    public string? ErrorMessage { get; set; }
}

public enum WorkflowExecutionStatus
{
    NotStarted,
    InProgress,
    Completed,
    Failed,
    Paused
}

public class WorkflowExecutionLog
{
    public DateTime Timestamp { get; set; }
    public string Message { get; set; } = string.Empty;
    public string LogLevel { get; set; } = string.Empty; // Info, Warning, Error
    public Dictionary<string, object>? Data { get; set; }
}

/// <summary>
/// Collaborative Recommendation Engine for team-based workflows.
/// </summary>
public interface ICollaborationRecommendationService
{
    Task<CollaborationSuggestion[]> SuggestCollaboratorsAsync(Guid projectId, Guid userId);
    Task<SkillGapAnalysis> AnalyzeTeamSkillsAsync(Guid projectId);
    Task<ProcessOptimizationSuggestion[]> SuggestProcessImprovementsAsync(Guid projectId);
}

public class CollaborationSuggestion
{
    public Guid SuggestedUserId { get; set; }
    public string Reason { get; set; } = string.Empty;
    public string[] ComplementarySkills { get; set; } = Array.Empty<string>();
    public double RelevanceScore { get; set; }
}

public class SkillGapAnalysis
{
    public string[] RequiredSkills { get; set; } = Array.Empty<string>();
    public string[] TeamSkills { get; set; } = Array.Empty<string>();
    public string[] MissingSkills { get; set; } = Array.Empty<string>();
    public string[] RecommendedTrainings { get; set; } = Array.Empty<string>();
}

public class ProcessOptimizationSuggestion
{
    public string Title { get; set; } = string.Empty;
    public string Description { get; set; } = string.Empty;
    public double PotentialTimeReduction { get; set; } // Percentage
    public string[] ImplementationSteps { get; set; } = Array.Empty<string>();
    public string Impact { get; set; } = string.Empty; // "High", "Medium", "Low"
}

/// <summary>
/// Performance Optimization Service using ML to improve workflows.
/// </summary>
public interface IPerformanceOptimizationService
{
    Task<OptimizationRecommendation[]> AnalyzeWorkflowPerformanceAsync(Guid projectId);
    Task<ResourceAllocationOptimization> OptimizeResourceAllocationAsync(Guid projectId);
    Task<TimeSeriesForecast> ForecastProjectCompletionAsync(Guid projectId);
}

public class OptimizationRecommendation
{
    public string Title { get; set; } = string.Empty;
    public string Description { get; set; } = string.Empty;
    public double ExpectedImprovement { get; set; }
    public string[] ActionItems { get; set; } = Array.Empty<string>();
    public int Priority { get; set; } // 1=high, 3=low
}

public class ResourceAllocationOptimization
{
    public Guid ProjectId { get; set; }
    public Dictionary<string, int> OptimalRoleDistribution { get; set; } = new();
    public Dictionary<string, double> TimeAllocationRecommendations { get; set; } = new();
}

public class TimeSeriesForecast
{
    public Guid ProjectId { get; set; }
    public DateTime ProjectedCompletionDate { get; set; }
    public double ConfidenceLevel { get; set; }
    public DateTime[] KeyMilestones { get; set; } = Array.Empty<DateTime>();
    public string RiskFactors { get; set; } = string.Empty;
}
