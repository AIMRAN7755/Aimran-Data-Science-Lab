using System;
using System.Collections.Generic;

namespace AimranDataScienceLab.Core.Domain.AI;

/// <summary>
/// AI Assistant that analyzes user requests and recommends workflows.
/// Provides intelligent suggestions across all roles.
/// </summary>
public class AIAssistantRequest
{
    public Guid Id { get; set; }
    public Guid ProjectId { get; set; }
    public Guid UserId { get; set; }

    public string UserQuery { get; set; } = string.Empty;
    public AIAssistantResponse? Response { get; set; }

    public DateTime CreatedAt { get; set; }
    public DateTime? RespondedAt { get; set; }
}

public class AIAssistantResponse
{
    public Guid Id { get; set; }
    public string SuggestedWorkflow { get; set; } = string.Empty;
    public string[] RecommendedSteps { get; set; } = Array.Empty<string>();

    public Guid[] RecommendedDatasets { get; set; } = Array.Empty<Guid>();
    public Guid[] RecommendedModels { get; set; } = Array.Empty<Guid>();

    public double ConfidenceScore { get; set; }
    public string[]? AlternativeApproaches { get; set; }

    public DateTime GeneratedAt { get; set; }
}

/// <summary>
/// Represents an auto-generated insight from the AI Insight Engine.
/// </summary>
public class AutoGeneratedInsight
{
    public Guid Id { get; set; }
    public Guid ProjectId { get; set; }
    public Guid DatasetId { get; set; }

    public string Title { get; set; } = string.Empty;
    public string Description { get; set; } = string.Empty;

    public InsightCategory Category { get; set; }
    public double Relevance { get; set; } // 0-1
    public double Confidence { get; set; } // 0-1

    public string[] SupportingMetrics { get; set; } = Array.Empty<string>();
    public string[] RelatedColumns { get; set; } = Array.Empty<string>();

    public bool IsReviewed { get; set; }
    public bool IsApproved { get; set; }
    public Guid? ReviewedByUserId { get; set; }

    public DateTime GeneratedAt { get; set; }
    public DateTime? ReviewedAt { get; set; }
}

public enum InsightCategory
{
    DistributionAnomalies,
    CorrelationPatterns,
    TimeSeriesTrends,
    OutlierDetection,
    ClusteringPatterns,
    MissingDataIssues,
    DataQualityWarnings,
    BusinessOpportunity,
    RiskIndicator,
    Recommendation
}

/// <summary>
/// Configuration for the auto-ML engine.
/// </summary>
public class AutoMLConfiguration
{
    public Guid Id { get; set; }
    public Guid ProjectId { get; set; }

    public Guid SourceDatasetId { get; set; }
    public string TargetVariable { get; set; } = string.Empty;

    public AutoMLTaskType TaskType { get; set; }
    public string[] AllowedAlgorithms { get; set; } = Array.Empty<string>();

    public int TimeoutMinutes { get; set; } = 60;
    public int MaxModelsToTrain { get; set; } = 10;

    public double ValidationSplit { get; set; } = 0.2;
    public string? TrainTestSplit { get; set; } // e.g., "0.8:0.2"

    public Dictionary<string, object> EvaluationMetrics { get; set; } = new();

    public bool UseEnsemble { get; set; } = true;
    public bool ApplyFeatureEngineering { get; set; } = true;

    public AutoMLStatus Status { get; set; } = AutoMLStatus.NotStarted;
    public Guid? BestModelId { get; set; }

    public DateTime CreatedAt { get; set; }
    public DateTime? StartedAt { get; set; }
    public DateTime? CompletedAt { get; set; }
}

public enum AutoMLTaskType
{
    BinaryClassification,
    MultiClassClassification,
    Regression,
    TimeSeries,
    Clustering,
    AnomalyDetection
}

public enum AutoMLStatus
{
    NotStarted,
    Running,
    Completed,
    Failed,
    Cancelled
}

/// <summary>
/// Recommendation engine for suggesting next steps in workflow.
/// </summary>
public class WorkflowRecommendation
{
    public Guid Id { get; set; }
    public Guid ProjectId { get; set; }
    public Guid UserId { get; set; }

    public WorkflowRecommendationType Type { get; set; }
    public string[] SuggestedActions { get; set; } = Array.Empty<string>();
    public string? Reasoning { get; set; }

    public double RelevanceScore { get; set; }
    public int Priority { get; set; } // 1=high, 3=low

    public DateTime CreatedAt { get; set; }
    public DateTime? ActedUponAt { get; set; }
    public bool IsImplemented { get; set; }
}

public enum WorkflowRecommendationType
{
    DataCleaning,
    FeatureEngineering,
    ModelSelection,
    HyperparameterTuning,
    ModelEvaluation,
    DataQualityImprovement,
    DriftDetection,
    ModelRetraining,
    DeploymentOptimization
}
